import { chromium } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';
const root = path.resolve('artifacts/phase-2/codex-review');
const evidence = path.join(root, 'evidence');
const identity = JSON.parse(await fs.readFile(path.join(evidence, 'identity.json')));
const prior = JSON.parse(await fs.readFile(path.join(evidence, 'repair-check.json')));
const flowUrl = prior.find(x => x.event === 'flow-nodes').flowUrl;
const state = JSON.parse(await fs.readFile(path.join(evidence, 'session.json')));
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ baseURL: 'http://localhost:3100', storageState: state, viewport: { width: 1440, height: 900 } });
const page = await context.newPage();
const events = [];
page.on('console', m => { if (m.type() === 'error') events.push({ event: 'console', text: m.text().replace(/params:\s*[^\n]+/g, 'params: [redacted]') }); });
page.on('response', r => { if (r.status() >= 400) events.push({ event: 'response', status: r.status(), url: r.url() }); });
const shot = async name => {
  await page.screenshot({ path: path.join(root, 'screenshots', `${name}.png`), fullPage: true });
  events.push({ event: 'state', name, url: page.url(), text: (await page.locator('body').innerText()).slice(0, 7000) });
  console.log(name);
};
try {
  await page.goto(flowUrl);
  await page.locator('.react-flow__node').nth(1).click();
  const mapping = await page.getByTestId('node-drawer').getByLabel('Input mapping (JSONata → object)').inputValue();
  const channel = mapping.match(/"channel":\s*"([^"]+)"/)?.[1];
  if (!channel) throw new Error('Could not read test channel');
  events.push({ event: 'flow', flowUrl, channel });
  await page.keyboard.press('Escape'); await page.keyboard.press('Escape');
  const revoke = await page.request.post('http://127.0.0.1:4010/__fake/revoke-account', { data: { account: 'a' } });
  events.push({ event: 'revoke', status: revoke.status(), body: await revoke.text() });
  await page.getByRole('button', { name: '▶ Run' }).click();
  await page.waitForTimeout(2500);
  await shot('67-revoked-slack-run');
  await page.goto(`/w/${identity.workspaceSlug}/integrations`);
  await shot('68-integrations-repair-banner');
  await page.goto(flowUrl);
  await shot('69-flow-paused');
  await page.goto(identity.builderUrl);
  await page.getByRole('button', { name: '▶ Run' }).click();
  await page.waitForTimeout(1800);
  await shot('70-other-flow-while-paused');
  await page.goto(`/w/${identity.workspaceSlug}/integrations`);
  await page.getByTestId('connection-slack').getByRole('button', { name: 'Reconnect' }).click();
  await shot('71-reconnect-same-account-dialog');
  await page.getByRole('dialog', { name: 'Reconnect Slack' }).getByRole('button', { name: 'Continue to Slack' }).click();
  await page.getByTestId('connection-slack').getByText('Connected').waitFor({ timeout: 15000 });
  await shot('72-slack-reconnected');
  await page.goto(flowUrl);
  await shot('73-flow-resumed-no-auto-run');
  await page.getByRole('button', { name: '▶ Run' }).click();
  await page.waitForTimeout(2000);
  await shot('74-reconnected-slack-run');
  const slack = await (await page.request.get('http://127.0.0.1:4010/__fake/state/slack')).json();
  events.push({ event: 'slack-provider-state', messages: slack.messages.filter(x => x.channel === channel) });
} catch (error) {
  events.push({ event: 'script-error', text: String(error), stack: error.stack });
  await shot('repair-resume-error').catch(() => {});
  console.error(error.stack || error);
} finally {
  await fs.writeFile(path.join(evidence, 'repair-resume.json'), JSON.stringify(events, null, 2));
  await fs.writeFile(path.join(evidence, 'session.json'), JSON.stringify(await context.storageState(), null, 2));
  await browser.close();
}
