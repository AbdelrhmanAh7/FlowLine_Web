import { chromium } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';
const root = path.resolve('artifacts/phase-2/codex-review');
const evidence = path.join(root, 'evidence');
const identity = JSON.parse(await fs.readFile(path.join(evidence, 'identity.json')));
const state = JSON.parse(await fs.readFile(path.join(evidence, 'session.json')));
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ baseURL: 'http://localhost:3100', storageState: state, viewport: { width: 1440, height: 900 } });
const page = await context.newPage();
const events = [];
page.on('console', m => { if (m.type() === 'error') events.push({ event: 'console', text: m.text().replace(/params:\s*[^\n]+/g, 'params: [redacted]') }); });
page.on('response', r => { if (r.status() >= 400) events.push({ event: 'response', status: r.status(), url: r.url() }); });
const shot = async name => {
  await page.screenshot({ path: path.join(root, 'screenshots', `${name}.png`), fullPage: true });
  events.push({ event: 'state', name, url: page.url(), text: (await page.locator('body').innerText()).slice(0, 7000) });
  console.log(name);
};
const close = async () => { await page.keyboard.press('Escape'); await page.keyboard.press('Escape'); };
const connect = async (from, to) => {
  const a = await page.locator(`.react-flow__node[data-id="${from}"] .react-flow__handle.source`).boundingBox();
  const b = await page.locator(`.react-flow__node[data-id="${to}"] .react-flow__handle.target`).boundingBox();
  await page.mouse.move(a.x+a.width/2,a.y+a.height/2); await page.mouse.down();
  await page.mouse.move(a.x+40,a.y+10,{steps:5});
  await page.mouse.move(b.x+b.width/2,b.y+b.height/2,{steps:12}); await page.mouse.up();
};
try {
  const slug = identity.workspaceSlug;
  await page.goto(`/w/${slug}/flows`);
  await page.getByRole('button', { name: '+ New flow' }).click();
  await page.getByText('Start with a trigger').waitFor();
  const pane = page.locator('.react-flow__pane');
  for (const [search, id, x] of [['webhook', 'palette-trigger.webhook', 350], ['action', 'palette-integration.action', 600], ['output', 'palette-output', 850]]) {
    await page.getByRole('button', { name: /Add node/ }).click();
    const palette = page.getByRole('dialog', { name: 'Add node' });
    await palette.getByLabel('Search nodes').fill(search);
    await palette.locator(`#${id.replaceAll('.', '\\.')}`).dragTo(pane, { targetPosition: { x, y: 480 } });
    await close();
  }
  const flowUrl = page.url();
  const ids = await page.locator('.react-flow__node').evaluateAll(els => els.map(e => e.getAttribute('data-id')));
  events.push({ event: 'flow-nodes', ids, flowUrl });
  if (ids.length !== 3) throw new Error(`Expected 3 nodes, got ${ids.length}`);
  await connect(ids[0], ids[1]); await connect(ids[1], ids[2]);
  await page.locator(`.react-flow__node[data-id="${ids[1]}"]`).click();
  const drawer = page.getByTestId('node-drawer');
  await drawer.getByLabel('App').selectOption('slack');
  await drawer.getByLabel('Action').selectOption('slack.post_message');
  const connection = drawer.getByLabel('Connection');
  const labels = await connection.locator('option').allTextContents();
  await connection.selectOption({ label: labels.find(x => x && !x.startsWith('Choose') && !x.startsWith('No ')) });
  const channel = `C_REPAIR_${Date.now().toString(36)}`;
  await drawer.getByLabel('Input mapping (JSONata → object)').fill(`{ "channel": "${channel}", "text": "Connection repair check" }`);
  await close();
  await page.locator(`.react-flow__node[data-id="${ids[2]}"]`).click();
  await drawer.getByLabel('Output key').fill('done');
  await close();
  await page.waitForTimeout(1200);
  await shot('65-slack-only-flow-configured');
  await page.getByRole('button', { name: 'Publish', exact: true }).click();
  await page.getByTestId('webhook-secret').waitFor({ timeout: 12000 });
  await page.getByRole('button', { name: 'Close triggers panel' }).click().catch(async () => { await page.getByRole('button', { name: '✕' }).first().click(); });
  await shot('66-slack-only-published');
  await fs.writeFile(path.join(evidence, 'repair-ids.json'), JSON.stringify({ flowUrl, channel }, null, 2));
  const revoke = await page.request.post('http://127.0.0.1:4010/__fake/revoke-account', { data: { account: 'a' } });
  events.push({ event: 'revoke', status: revoke.status(), body: await revoke.text() });
  await page.getByRole('button', { name: '▶ Run' }).click();
  await page.waitForTimeout(2200);
  await shot('67-revoked-slack-run');
  await page.goto(`/w/${slug}/integrations`);
  await shot('68-integrations-repair-banner');
  await page.goto(flowUrl);
  await shot('69-flow-paused');
  await page.goto(identity.builderUrl);
  await page.getByRole('button', { name: '▶ Run' }).click();
  await page.waitForTimeout(1800);
  await shot('70-other-flow-while-paused');
  await page.goto(`/w/${slug}/integrations`);
  await page.getByTestId('connection-slack').getByRole('button', { name: 'Reconnect' }).click();
  await shot('71-reconnect-same-account-dialog');
  await page.getByRole('dialog', { name: 'Reconnect Slack' }).getByRole('button', { name: 'Continue to Slack' }).click();
  await page.getByTestId('connection-slack').getByText('Connected').waitFor({ timeout: 15000 });
  await shot('72-slack-reconnected');
  await page.goto(flowUrl);
  await shot('73-flow-resumed-no-auto-run');
  await page.getByRole('button', { name: '▶ Run' }).click();
  await page.waitForTimeout(2000);
  await shot('74-reconnected-slack-run');
  const slack = await (await page.request.get('http://127.0.0.1:4010/__fake/state/slack')).json();
  events.push({ event: 'slack-provider-state', messages: slack.messages.filter(x => x.channel === channel) });
} catch (error) {
  events.push({ event: 'script-error', text: String(error), stack: error.stack });
  await shot('repair-check-error').catch(() => {});
  console.error(error.stack || error);
} finally {
  await fs.writeFile(path.join(evidence, 'repair-check.json'), JSON.stringify(events, null, 2));
  await fs.writeFile(path.join(evidence, 'session.json'), JSON.stringify(await context.storageState(), null, 2));
  await browser.close();
}
