import {execFileSync} from 'node:child_process';
import {readFileSync,writeFileSync} from 'node:fs';
const out='artifacts/beta-execution/20260930-landing-executor';
const git=(...args)=>execFileSync('git',args,{encoding:'utf8',maxBuffer:64*1024*1024,stdio:['ignore','pipe','pipe']}).trim();
if(git('branch','--show-current')!=='design-v2'||git('rev-parse','HEAD')!=='776337cec8ed5ee823017f40020459e28cf0467a')throw Error('Unexpected source branch/head; preserved');
if(git('diff','--cached','--name-only'))throw Error('Existing real-index work; preserved');
const gate=JSON.parse(readFileSync(`${out}/cp28r1-browsers.json`));
if(gate.state!=='PASS')throw Error('Final browser run incomplete');
const gates=JSON.parse(readFileSync(`${out}/cp28-nonbrowser-gates.json`));
if(gates.sequence.length!==7||gates.sequence.some(x=>x.exitCode!==0))throw Error('Non-browser gate incomplete');
const chrome=JSON.parse(readFileSync(`${out}/chrome-main-handoff/REPORT.json`));
if(chrome.state!=='PASS')throw Error('Chrome header retest incomplete');
const manifest=JSON.parse(readFileSync(`${out}/main-staging-manifest.json`));
for(let i=0;i<manifest.paths.length;i+=30)git('add','--',...manifest.paths.slice(i,i+30));
const staged=git('diff','--cached','--name-only','-z').split('\0').filter(Boolean).sort();
if(JSON.stringify(staged)!==JSON.stringify(manifest.paths))throw Error('Staged path mismatch; preserved for inspection');
const tree=git('write-tree');
const cp=JSON.parse(readFileSync(`${out}/checkpoint-28.json`));
const mapping=Object.fromEntries(Object.entries(cp.inputs).map(([p,v])=>[p,{checkpoint:v,staged:git('rev-parse',tree+':'+p)}]));
if(Object.values(mapping).some(v=>v.checkpoint!==v.staged))throw Error('Frozen execution inputs do not match; preserved');
writeFileSync(`${out}/staged-main-identity.json`,JSON.stringify({at:new Date().toISOString(),tree,checkpoint:cp.commit,paths:staged.length,mapping,originalWebKitReliability:'OPEN'},null,2));
console.log(JSON.stringify({stagedPaths:staged.length,executionInputsMatched:10,tree}));
