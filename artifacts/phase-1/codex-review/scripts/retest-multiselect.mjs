import { chromium } from '@playwright/test';
import { readFileSync, writeFileSync } from 'node:fs';
const root='artifacts/phase-1/codex-review';
const prior=JSON.parse(readFileSync(`${root}/retest-journey-results.json`,'utf8'));
const result={events:[]};
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({baseURL:'http://localhost:3100',viewport:{width:1440,height:900}});
const page=await context.newPage();
page.on('response',r=>{if(r.status()>=400) result.events.push({status:r.status(),url:r.url()});});
const snap=async name=>page.screenshot({path:`${root}/screenshots/retest-${name}.png`});
const selected=()=>page.locator('.react-flow__node.selected').evaluateAll(es=>es.map(e=>e.getAttribute('data-id')));
try {
  await page.goto('/sign-in');
  await page.getByLabel('Email').fill(prior.email);
  await page.getByLabel('Password').fill('Codex-Test-Pass-1');
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await page.waitForURL(/\/w\//,{timeout:45000});
  await page.goto('/w/codex-retest/flows/b0b9d277-8b6c-4baa-80ab-9beebcca589b');
  await page.locator('.react-flow__node').first().waitFor();
  const ids=await page.locator('.react-flow__node').evaluateAll(es=>es.map(e=>e.getAttribute('data-id')));
  result.before=ids;
  const trigger=page.locator(`.react-flow__node[data-id="${ids[0]}"]`);
  const output=page.locator(`.react-flow__node[data-id="${ids.at(-1)}"]`);
  await output.click({position:{x:10,y:40}});
  await page.keyboard.down('Control'); await trigger.click(); await page.keyboard.up('Control');
  result.ctrlSelected=await selected(); await snap('multiselect-ctrl-click');
  await page.keyboard.press('Backspace');
  result.afterBackspace=await page.locator('.react-flow__node').evaluateAll(es=>es.map(e=>e.getAttribute('data-id')));
  await snap('multiselect-backspace-deleted');
  console.log(JSON.stringify(result));
} finally {writeFileSync(`${root}/retest-multiselect-results.json`,JSON.stringify(result,null,2));await browser.close();}
